export function t(key, params = {}) {
  const lang = store.lang === 'te' ? 'te' : 'en';
  let text = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

export function gemSummary(gem) {
  if (!gem) return '';
  if (store.lang === 'te') {
    if (gem.summary_te) return gem.summary_te;
    if (gem.story_te) {
      const s = String(gem.story_te).trim();
      return s.length > 130 ? `${s.slice(0, 127)}...` : s;
    }
  }
  return gem.summary || '';
}

export function localizeState(stateName) {
  if (store.lang !== 'te') return stateName;
  if (stateName === 'Telangana') return t('stateTelangana');
  if (stateName === 'Andhra Pradesh') return t('stateAndhra');
  return stateName;
}

export function localizeRegion(region = '') {
  if (store.lang !== 'te') return region;
  return String(region)
    .replace('Telangana', t('stateTelangana'))
    .replace('Andhra Pradesh', t('stateAndhra'));
}
